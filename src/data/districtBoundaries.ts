export const getRiskFillColor = (risk: RiskLevel, alpha = 0.45): string => {
  switch (risk) {
    case 'แดง':
      return `rgba(220, 38, 38, ${alpha})`;
    case 'ส้ม':
      return `rgba(234, 88, 12, ${alpha})`;
    case 'เหลือง':
      return `rgba(234, 179, 8, ${alpha})`;
    case 'เขียว':
      return `rgba(22, 163, 74, ${alpha})`;
    default:
      return `rgba(100, 116, 139, ${alpha})`;
  }
};

export const getRiskBorderColor = (risk: RiskLevel): string => {
  switch (risk) {
    case 'แดง':
      return '#ef4444';
    case 'ส้ม':
      return '#f97316';
    case 'เหลือง':
      return '#eab308';
    case 'เขียว':
      return '#22c55e';
    default:
      return '#94a3b8';
  }
};
